_WORD_CHARS = re.compile(r"[^a-z0-9&+.'=\- ]+")
_SPACES = re.compile(r"\s+")


def normalize(text: str) -> str:
    """Lower-case ``text`` and strip the punctuation that varies between banks.

    Apostrophes, ampersands, plus and equals signs, dots and hyphens are kept
    because a few merchants are only recognisable with them ("h&m", "disney+",
    "lv=").  Runs of whitespace collapse to a single space and the result is
    wrapped in single spaces so that a pattern written as ``" bar "`` only
    matches the whole word.
    """
    lowered = text.lower().replace("\u2019", "'").replace("`", "'")
    cleaned = _WORD_CHARS.sub(" ", lowered)
    return " " + _SPACES.sub(" ", cleaned).strip() + " "


def _compile(rules: Iterable[Rule]) -> List[Tuple[str, str, str]]:
    """Normalise the patterns, keep their word anchors and reject bad rules."""
    seen: Dict[str, int] = {}
    out: List[Tuple[str, str, str]] = []
    for index, (pattern, category, subcategory) in enumerate(rules):
        if not pattern or not pattern.strip():
            raise ValueError(f"rule {index}: empty pattern")
        if category not in CATEGORIES:
            raise ValueError(f"rule {index}: unknown category {category!r}")
        key = normalize(pattern).strip()
        if key in seen:
            raise ValueError(f"rule {index}: duplicate pattern {pattern!r} (first at {seen[key]})")
        seen[key] = index
        needle = key
        if pattern.startswith(" "):
            needle = " " + needle
        if pattern.endswith(" "):
            needle = needle + " "
        out.append((needle, category, subcategory))
    return out


_COMPILED: List[Tuple[str, str, str]] = _compile(RULES)


def match(payee: str, memo: str = "") -> Optional[Rule]:
    """Return the first rule matching ``payee`` (then ``memo``), or ``None``.

    The returned pattern is the normalised form without its word anchors.
    """
    haystacks = [normalize(payee)]
    if memo:
        haystacks.append(normalize(memo))
    for haystack in haystacks:
        for needle, category, subcategory in _COMPILED:
            if needle in haystack:
                return (needle.strip(), category, subcategory)
    return None


def categorize(transaction: Transaction, overwrite: bool = False) -> Transaction:
    """Return ``transaction`` with ``category``/``subcategory`` filled from the rules.

    A transaction that already carries a category is returned unchanged
    unless ``overwrite`` is true.  When no rule matches the category becomes
    ``UNCATEGORIZED`` so that reports never have an empty group label.
    """
    if transaction.category and not overwrite:
        return transaction
    found = match(transaction.payee, transaction.memo)
    if found is None:
        return transaction.with_category(UNCATEGORIZED, "")
    _, category, subcategory = found
    return transaction.with_category(category, subcategory)


def categorize_all(transactions: Iterable[Transaction], overwrite: bool = False) -> List[Transaction]:
    """Apply :func:`categorize` to every transaction and return a new list."""
    return [categorize(t, overwrite=overwrite) for t in transactions]


def rule_count() -> int:
    """Number of rules in the table."""
    return len(_COMPILED)


def categories_in_use() -> List[str]:
    """Distinct categories referenced by the rules table, in table order."""
    seen: List[str] = []
    for _, category, _ in _COMPILED:
        if category not in seen:
            seen.append(category)
    return seen
